/**
 * @file zadanie1.cpp
 * @brief Программа для демонстрации работы с массивом целых чисел.
 *
 * Программа выполняет три операции над массивом из 10 целых чисел:
 *  - заполнение с клавиатуры;
 *  - обмен первого и последнего элементов;
 *  - умножение всех элементов на два.
 *
 * @author krkastudent Погосян Даниил 606-42
 * @date 2026
 */

#include <iostream>
using namespace std;

/**
 * @brief Заполняет массив из 10 элементов значениями, введёнными пользователем.
 *
 * Функция последовательно считывает 10 целых чисел из стандартного потока ввода
 * и записывает их в переданный массив.
 *
 * @param arr Ссылка на массив из 10 целых чисел, который будет заполнен.
 *
 * @note Размер массива фиксирован и равен 10 элементам.
 * @warning При вводе нечисловых значений поток переходит в состояние ошибки.
 */
void fillArray(int (&arr)[10]) {
    cout << "Введите 10 целых чисел: " << endl;
    for (int i = 0; i < 10; i++) {
        cin >> arr[i];
    }
}

/**
 * @brief Выводит содержимое массива из 10 элементов в стандартный поток вывода.
 *
 * @param arr Константная ссылка на массив из 10 целых чисел.
 *
 * @details Элементы разделяются пробелом, после последнего элемента
 *          выводится символ перевода строки.
 */
void printArray(int (&arr)[10]) {
    for (auto& x : arr) {
        cout << x << " ";
    }
    cout << "\n";
}

/**
 * @brief Меняет местами два элемента массива по заданным индексам.
 *
 * @param arr    Ссылка на массив из 10 целых чисел.
 * @param first  Индекс первого элемента для обмена.
 * @param second Индекс второго элемента для обмена.
 *
 * @warning Функция не проверяет корректность индексов. Выход за пределы
 *          диапазона [0, 9] приводит к неопределённому поведению.
 */
void swapElements(int (&arr)[10], int& first, int& second) {
    int tmp = arr[first];
    arr[first] = arr[second];
    arr[second] = tmp;
}

/**
 * @brief Умножает каждый элемент массива на два.
 *
 * @param arr Ссылка на массив из 10 целых чисел.
 *
 * @note Изменения применяются непосредственно к исходному массиву.
 */
void multiplyByTwo(int (&arr)[10]) {
    for (int& x : arr) {
        x *= 2;
    }
}

/**
 * @brief Точка входа в программу.
 *
 * Последовательно выполняет:
 *  1. заполнение массива пользователем;
 *  2. вывод исходного массива;
 *  3. обмен первого и последнего элементов;
 *  4. вывод массива после обмена;
 *  5. умножение всех элементов на два;
 *  6. вывод итогового массива.
 *
 * @return 0 при успешном завершении программы.
 */
int main() {
    /// Массив из 10 целых чисел, с которым выполняются операции.
    int array[10];

    fillArray(array);

    cout << "Исходный массив: ";
    printArray(array);

    /// Индекс первого элемента для обмена.
    int first = 0;
    /// Индекс последнего элемента для обмена.
    int second = 9;

    swapElements(array, first, second);
    cout << "Массив после обмена первого и последнего элемента: ";
    printArray(array);

    multiplyByTwo(array);
    cout << "Массив после умножения всех элементов на два: ";
    printArray(array);

    return 0;
}
