/**
 * @file zadanie2.cpp
 * @brief Обработка динамического массива целых чисел.
 *
 * Программа:
 *  - запрашивает размер массива N и его элементы;
 *  - выводит исходный массив;
 *  - находит индекс первого отрицательного элемента;
 *  - если такой элемент есть, обрезает массив до элементов, стоящих перед ним;
 *  - освобождает память и обнуляет указатель.
 *
 * @author krkastudent Погосян Даниил 606-42
 * @date 2026
 */

#include <iostream>
using namespace std;

/**
 * @brief Обрабатывает динамический массив: находит первый отрицательный
 *        элемент и обрезает массив до позиции перед ним.
 *
 * @param[in,out] arr  Ссылка на указатель на динамический массив.
 *                     При обрезании старое содержимое освобождается, а указатель
 *                     перенаправляется на новый массив меньшего размера.
 *                     Если отрицательных элементов нет, указатель не меняется.
 * @param[in,out] size Ссылка на размер массива. После обрезания содержит
 *                     индекс первого отрицательного элемента (новый размер).
 *
 * @details Алгоритм работы:
 *  1. Линейный поиск первого элемента со значением < 0.
 *  2. Если элемент не найден — массив остаётся без изменений.
 *  3. Если найден — создаётся новый массив длиной `negIndex`, куда
 *     копируются все элементы исходного массива до найденного индекса.
 *  4. Старый массив освобождается через `delete[]`, указатель и размер
 *     обновляются.
 *
 * @note Функция изменяет владельца памяти: после вызова `arr` указывает
 *       на новый массив, который должен быть освобождён вызывающей стороной.
 * @warning Если `arr == nullptr`, поведение не определено.
 * @warning Не проверяет отрицательное значение `size`. При `size < 0`
 *          возможен выход за границы массива.
 */
void process(int*& arr, int& size) {
    /// Индекс первого отрицательного элемента; -1, если не найден.
    int negIndex = -1;

    for (int i = 0; i < size; i++) {
        if (arr[i] < 0) {
            negIndex = i;
            break;
        }
    }

    cout << "Первый отрицательный элемент на индексе: " << negIndex << "\n";

    if (negIndex != -1) {
        /// Новый массив, содержащий только элементы до первого отрицательного.
        int* newArr = new int[negIndex]{};
        for (int i = 0; i < negIndex; i++) {
            newArr[i] = arr[i];
        }

        delete[] arr;      ///< Освобождаем старую память.
        arr = newArr;      ///< Перенаправляем указатель на новый массив.
        size = negIndex;   ///< Обновляем размер массива.
    }
}

/**
 * @brief Точка входа в программу.
 *
 * Последовательно выполняет:
 *  1. Ввод размера массива N.
 *  2. Выделение динамической памяти под массив.
 *  3. Ввод N целых чисел.
 *  4. Вывод исходного массива.
 *  5. Обработку массива через функцию process().
 *  6. Вывод результата.
 *  7. Освобождение памяти и обнуление указателя.
 *
 * @return 0 при успешном завершении программы.
 *
 * @note Если после обработки размер массива равен нулю, выводится
 *       сообщение «(массив пуст)».
 */
int main() {
    // 1. Спрашиваем размер массива
    int N;  ///< Размер массива, вводимый пользователем.
    cout << "Введите размер массива N: ";
    cin >> N;

    // 2. Выделяем память под массив
    int* arr = new int[N]{};  ///< Динамический массив из N элементов, инициализирован нулями.

    cout << "Введите " << N << " целых чисел: " << endl;
    for (int i = 0; i < N; i++) {
        cin >> arr[i];
    }

    cout << "Введённый массив: ";
    for (int i = 0; i < N; i++) {
        cout << arr[i] << " ";
    }
    cout << "\n";

    // 3. Обрабатываем массив
    process(arr, N);

    // 4. Выводим результат
    cout << "Результат: ";
    if (N == 0) {
        cout << "(массив пуст)";
    } else {
        for (int i = 0; i < N; i++) {
            cout << arr[i] << " ";
        }
    }
    cout << "\n";

    // 5. Освобождаем память и обнуляем указатель
    delete[] arr;
    arr = nullptr;

    if (arr == nullptr) {
        cout << "Указатель обнулён, обращение к памяти невозможно "
                "(dangling pointer исключён)." << endl;
    } else {
        cout << arr[0] << endl;
    }

    return 0;
}
